#List 
marks = [85, 92, 78, 96, 88]
print(marks)
marks.append(49)
print(marks)  

marks.sort()
print(marks) 

marks.sort(reverse=True)
print(marks) 

marks.reverse()
print(marks) 

marks.insert(3, 67)
print(marks) 

marks.remove(67)
print(marks) 

marks.pop(3)
print(marks) 

#Tuple
marks = (34,54,67,23,77)
print(marks) 

print(marks[2])

print(marks[2:5]) 

print(marks.count(7)) 